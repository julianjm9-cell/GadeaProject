const {chromium}=require('C:/Users/julia/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
  page.on('pageerror',error=>errors.push(error.stack));
  await page.goto(pathToFileURL(path.resolve('apps/profesor/index.html')).href);
  await page.evaluate(()=>{state.library.push({id:'visual-test',title:'Los colores',subject:'Matemáticas',kind:'Actividad interactiva',body:'',activity:{version:1,context:{course:'3.º Primaria',theme:''},questions:[{id:'q1',type:'gaps',prompt:'El cielo es ___.',answer:'azul',text:'',options:[]}]}},{id:'upload-test',title:'Mis apuntes',subject:'Lengua',kind:'Material propio',body:'Apuntes subidos por el profesor.',attachment:{id:'file',filename:'apuntes.pdf'}});render()});
  await page.locator('.home-primary-nav').getByRole('button',{name:'Material'}).click();
  const cards=page.locator('.material-hub-card');
  assert.ok(await cards.count()>0);
  assert.equal(await cards.locator('.material-art img').count(),await cards.count());
  await page.waitForFunction(()=>[...document.querySelectorAll('.material-art img')].every(image=>image.complete&&image.naturalWidth>0));
  const activityId='visual-test';
  const card=page.locator('.material-hub-card').filter({has:page.locator(`[data-id="${activityId}"]`)});
  assert.equal(await card.locator('[data-action="editMaterial"]').count(),1);
  assert.equal(await card.locator('.material-open').count(),1);
  await page.screenshot({path:'tools/profesor-material-visual.png',fullPage:true});
  assert.match(await card.locator('.material-art img').getAttribute('src'),/basic-gaps\.webp$/);
  assert.equal(await card.locator('.material-course').innerText(),'3.º Primaria');
  assert.equal(await card.locator('.material-course').evaluate(element=>getComputedStyle(element).backgroundColor), 'rgb(245, 248, 252)');
  const uploaded=page.locator('.material-hub-card').filter({has:page.locator('[data-id="upload-test"]')});
  assert.match(await uploaded.locator('.material-art img').getAttribute('src'),/uploaded-material\.webp$/);
  await card.locator('.material-open').click();
  await card.getByRole('button',{name:'Usar yo'}).click();
  assert.ok(await page.locator('#dialog[open] #activityScore').count());
  await page.locator('#dialog .close').click();
  await card.locator('.material-card-menu>summary').click();
  await card.locator('[data-action="editMaterial"]').click();
  assert.equal(await page.locator('#activityTitle').inputValue(),'Los colores');
  await page.locator('#dialog .close').click();
  assert.equal(await page.evaluate(()=>state.activityAttempts?.length||0),0);
  const gameCard=page.locator('.material-hub-card').filter({has:page.locator('[data-id="game0"]')});
  await gameCard.locator('.material-open').click();
  await page.locator('#plainAnswer').fill('3');
  await page.getByRole('button',{name:'Comprobar',exact:true}).click();
  assert.match(await page.locator('#plainFeedback').innerText(),/Correcto/);
  await page.locator('#dialog').getByRole('button',{name:'Cancelar'}).click();
  await gameCard.locator('.material-card-menu>summary').click();
  await gameCard.locator('[data-action="editMaterial"]').click();
  assert.equal(await page.locator('#plainSolution').inputValue(),'3');
  await page.locator('#dialog').getByRole('button',{name:'Cancelar'}).click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
  assert.ok(await cards.first().evaluate(card=>card.getBoundingClientRect().width>330));
  assert.deepEqual(errors,[]);
  console.log('PASS visual material cards, uploaded-file artwork, direct play and editing');
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)});
